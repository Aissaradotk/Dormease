function cleanVal(val) {
  if (val == null || val === "") return "";
  const num = Number(val);
  return isNaN(num) ? "" : String(num);
}

export default function BillSlipModal({ bill, onClose, onBillUpdated, canEdit }) {
  const { user } = useAuth();
  const { lang } = useLanguage();
  const t = T[lang] || T.th;

  const isOwner = canEdit !== undefined ? canEdit : (user?.role === "owner" || user?.role === "admin");

  const [currentBill, setCurrentBill] = useState(bill || {});
  const [isEditing, setIsEditing] = useState(false);
  const [editPrices, setEditPrices] = useState({
    room_price: cleanVal(bill?.room_price),
    water_price: cleanVal(bill?.water_price),
    electric_price: cleanVal(bill?.electric_price),
    other_fees: cleanVal(bill?.other_fees),
  });
  const [saving, setSaving] = useState(false);
  const [toastMsg, setToastMsg] = useState("");
  const [copied, setCopied] = useState(false);
  const [imgError, setImgError] = useState(false);
  const [verifying, setVerifying] = useState(false);

  async function handleConfirmPaid() {
    if (!currentBill?.id) return;
    setVerifying(true);
    try {
      const res = await api.post("/bills/confirm-paid", { bill_id: currentBill.id });
      if (res?.bill) {
        setCurrentBill(res.bill);
        if (onBillUpdated) onBillUpdated(res.bill);
        setToastMsg(lang === "en" ? "✓ Payment verified and approved successfully!" : "✓ ตรวจสอบยอดเงินสำเร็จ! อนุมัติการชำระเงินเรียบร้อยแล้ว");
      }
    } catch (err) {
      setToastMsg("✕ " + (err.message || (lang === "en" ? "Failed to verify payment" : "เกิดข้อผิดพลาดในการตรวจสอบยอดเงิน")));
    } finally {
      setVerifying(false);
    }
  }

  if (!bill) return null;

  const PROMPTPAY_NUMBER = "0996144478";
  const PROMPTPAY_FORMATTED = "099-614-4478";
  const PROMPTPAY_NAME = "หอพัก DormEase (PromptPay)";

  const roomNum = currentBill.room_number || bill.room_number || "-";
  const tenantName = currentBill.tenant_name || bill.tenant_name || currentBill.full_name || bill.full_name || t.tenant_fallback(roomNum);
  const period = currentBill.period || bill.period || bill.billing_month || new Date().toISOString().slice(0, 7);

  // คำนวณราคาปัจจุบัน (ขึ้นกับว่าอยู่ในโหมดแก้ไขหรือไม่)
  const activeRoomPrice = isEditing ? (Number(editPrices.room_price) || 0) : Number(currentBill.room_price ?? bill.room_price ?? 0);
  const activeWaterPrice = isEditing ? (Number(editPrices.water_price) || 0) : Number(currentBill.water_price ?? bill.water_price ?? 0);
  const activeElectricPrice = isEditing ? (Number(editPrices.electric_price) || 0) : Number(currentBill.electric_price ?? bill.electric_price ?? 0);
  const activeOtherFees = isEditing ? (Number(editPrices.other_fees) || 0) : Number(currentBill.other_fees ?? bill.other_fees ?? 0);

  const total = Number((activeRoomPrice + activeWaterPrice + activeElectricPrice + activeOtherFees).toFixed(2));
  const isPaid = (currentBill.status || currentBill.bill_status || bill.status || bill.bill_status) === "paid";
  const invoiceNo = `INV-${period.replace("-", "")}-${String(currentBill.bill_id || currentBill.id || currentBill.room_id || bill.room_id || 1).padStart(4, "0")}`;

  function handleCopyPromptPay() {
    navigator.clipboard.writeText(PROMPTPAY_NUMBER);
    setCopied(true);
    setTimeout(() => setCopied(false), 2500);
  }

  function handlePrint() {
    window.print();
  }

  function handleStartEdit() {
    setEditPrices({
      room_price: cleanVal(currentBill.room_price ?? bill.room_price),
      water_price: cleanVal(currentBill.water_price ?? bill.water_price),
      electric_price: cleanVal(currentBill.electric_price ?? bill.electric_price),
      other_fees: cleanVal(currentBill.other_fees ?? bill.other_fees),
    });
    setIsEditing(true);
  }

  async function handleSavePrices() {
    setSaving(true);
    try {
      const res = await api.post("/bills/save", {
        room_id: currentBill.room_id || bill.room_id,
        tenant_id: currentBill.tenant_id ?? bill.tenant_id,
        period: period,
        room_price: activeRoomPrice,
        water_price: activeWaterPrice,
        electric_price: activeElectricPrice,
        other_fees: activeOtherFees,
        status: currentBill.status || currentBill.bill_status || bill.status || bill.bill_status,
      });

      const updated = {
        ...currentBill,
        ...res,
        room_price: activeRoomPrice,
        water_price: activeWaterPrice,
        electric_price: activeElectricPrice,
        other_fees: activeOtherFees,
        total_amount: total,
      };

      setCurrentBill(updated);
      setIsEditing(false);
      setToastMsg(t.save_success);
      setTimeout(() => setToastMsg(""), 3500);

      if (onBillUpdated) {
        onBillUpdated(updated);
      }
    } catch (err) {
      alert("เกิดข้อผิดพลาดในการบันทึกราคาใบบิล: " + err.message);
    } finally {
      setSaving(false);
    }
  }

  const qrAmount = total % 1 === 0 ? total : total.toFixed(2);
  const qrUrl = `https://promptpay.io/${PROMPTPAY_NUMBER}/${qrAmount}.png`;

  return (
    <Modal title={t.modal_title} onClose={onClose}>
      {toastMsg && (
        <div
          style={{
            background: "#ecfdf5",
            color: "#065f46",
            border: "1px solid #a7f3d0",
            borderRadius: 8,
            padding: "10px 14px",
            marginBottom: 12,
            fontWeight: 700,
            fontSize: 13.5,
            display: "flex",
            alignItems: "center",
            gap: 8,
            animation: "fadeIn 0.2s ease-in-out",
          }}
        >
          <span>✓</span>
          <span>{toastMsg}</span>
        </div>
      )}

      <div className="bill-slip-container notranslate" id="printable-bill-slip" translate="no">
        {/* Header */}
        <div className="slip-header">
          <div className="slip-dorm-brand">
            <div className="slip-logo-badge">🏠 DORMEASE</div>
            <div className="slip-dorm-title">{t.dorm_name}</div>
            <div className="slip-dorm-subtitle">{t.dorm_sub(PROMPTPAY_FORMATTED)}</div>
          </div>
          <div className="slip-meta">
            <div className="slip-inv-num">{invoiceNo}</div>
            <div className="slip-date">{t.period_lbl} <strong>{period}</strong></div>
            <div style={{ display: "flex", gap: 6, justifyContent: "flex-end", alignItems: "center", marginTop: 4 }}>
              {isEditing && (
                <span style={{ fontSize: 11, background: "#fef3c7", color: "#92400e", border: "1px solid #fde68a", padding: "2px 8px", borderRadius: 99, fontWeight: 700 }}>
                  {t.editing_badge}
                </span>
              )}
              <div className={`slip-status-tag ${isPaid ? "paid" : "unpaid"}`}>
                {isPaid ? t.status_paid : t.status_unpaid}
              </div>
            </div>
          </div>
        </div>

        <div className="slip-divider" />

        {/* Info Grid */}
        <div className="slip-info-grid">
          <div className="slip-info-box">
            <span className="slip-info-label">{t.lbl_room}</span>
            <span className="slip-info-val highlight">{t.room_prefix} {roomNum}</span>
          </div>
          <div className="slip-info-box">
            <span className="slip-info-label">{t.lbl_tenant}</span>
            <span className="slip-info-val">{tenantName}</span>
          </div>
          <div className="slip-info-box">
            <span className="slip-info-label">{t.lbl_room_type}</span>
            <span className="slip-info-val">{currentBill.room_type || bill.room_type || t.default_type}</span>
          </div>
          <div className="slip-info-box">
            <span className="slip-info-label">{t.lbl_issue_date}</span>
            <span className="slip-info-val">{new Date().toLocaleDateString(lang === "en" ? "en-US" : "th-TH")}</span>
          </div>
        </div>

        {/* Itemized Table */}
        <table className="slip-table">
          <thead>
            <tr>
              <th style={{ width: 40, textAlign: "center" }}>{t.th_no}</th>
              <th>{t.th_desc}</th>
              <th style={{ textAlign: "right", width: isEditing ? 140 : 120 }}>{t.th_amt}</th>
            </tr>
          </thead>
          <tbody>
            <tr>
              <td style={{ textAlign: "center" }}>1</td>
              <td>
                <b>{t.item_rent}</b>
                <span className="slip-item-sub">{t.item_rent_sub(period)}</span>
              </td>
              <td style={{ textAlign: "right" }}>
                {isEditing ? (
                  <input
                    type="number"
                    step="any"
                    value={editPrices.room_price}
                    onFocus={(e) => e.target.select()}
                    onChange={(e) => setEditPrices({ ...editPrices, room_price: e.target.value })}
                    onKeyDown={(e) => {
                      if (e.key === "Enter") {
                        e.preventDefault();
                        handleSavePrices();
                      }
                    }}
                    style={{
                      width: 95,
                      textAlign: "right",
                      padding: "4px 8px",
                      borderRadius: 6,
                      border: "1.5px solid var(--primary)",
                      fontWeight: 700,
                      fontSize: 14,
                      background: "#fff",
                    }}
                    autoFocus
                  />
                ) : (
                  <span>{activeRoomPrice.toLocaleString()} ฿</span>
                )}
              </td>
            </tr>
            <tr>
              <td style={{ textAlign: "center" }}>2</td>
              <td>
                <b>{t.item_water}</b>
                <span className="slip-item-sub">{t.item_water_sub}</span>
              </td>
              <td style={{ textAlign: "right" }}>
                {isEditing ? (
                  <input
                    type="number"
                    step="any"
                    value={editPrices.water_price}
                    onFocus={(e) => e.target.select()}
                    onChange={(e) => setEditPrices({ ...editPrices, water_price: e.target.value })}
                    onKeyDown={(e) => {
                      if (e.key === "Enter") {
                        e.preventDefault();
                        handleSavePrices();
                      }
                    }}
                    style={{
                      width: 95,
                      textAlign: "right",
                      padding: "4px 8px",
                      borderRadius: 6,
                      border: "1.5px solid var(--primary)",
                      fontWeight: 700,
                      fontSize: 14,
                      background: "#fff",
                    }}
                  />
                ) : (
                  <span>{activeWaterPrice.toLocaleString()} ฿</span>
                )}
              </td>
            </tr>
            <tr>
              <td style={{ textAlign: "center" }}>3</td>
              <td>
                <b>{t.item_electric}</b>
                <span className="slip-item-sub">{t.item_electric_sub}</span>
              </td>
              <td style={{ textAlign: "right" }}>
                {isEditing ? (
                  <input
                    type="number"
                    step="any"
                    value={editPrices.electric_price}
                    onFocus={(e) => e.target.select()}
                    onChange={(e) => setEditPrices({ ...editPrices, electric_price: e.target.value })}
                    onKeyDown={(e) => {
                      if (e.key === "Enter") {
                        e.preventDefault();
                        handleSavePrices();
                      }
                    }}
                    style={{
                      width: 95,
                      textAlign: "right",
                      padding: "4px 8px",
                      borderRadius: 6,
                      border: "1.5px solid var(--primary)",
                      fontWeight: 700,
                      fontSize: 14,
                      background: "#fff",
                    }}
                  />
                ) : (
                  <span>{activeElectricPrice.toLocaleString()} ฿</span>
                )}
              </td>
            </tr>
            {(isEditing || activeOtherFees > 0) && (
              <tr>
                <td style={{ textAlign: "center" }}>4</td>
                <td>
                  <b>{t.item_other}</b>
                  <span className="slip-item-sub">{t.item_other_sub}</span>
                </td>
                <td style={{ textAlign: "right" }}>
                  {isEditing ? (
                    <input
                      type="number"
                      step="any"
                      placeholder="0"
                      value={editPrices.other_fees}
                      onFocus={(e) => e.target.select()}
                      onChange={(e) => setEditPrices({ ...editPrices, other_fees: e.target.value })}
                      onKeyDown={(e) => {
                        if (e.key === "Enter") {
                          e.preventDefault();
                          handleSavePrices();
                        }
                      }}
                      style={{
                        width: 95,
                        textAlign: "right",
                        padding: "4px 8px",
                        borderRadius: 6,
                        border: "1.5px solid var(--primary)",
                        fontWeight: 700,
                        fontSize: 14,
                        background: "#fff",
                      }}
                    />
                  ) : (
                    <span>{activeOtherFees.toLocaleString(undefined, { minimumFractionDigits: 2, maximumFractionDigits: 2 })} ฿</span>
                  )}
                </td>
              </tr>
            )}
          </tbody>
          <tfoot>
            <tr className="slip-total-row">
              <td colSpan="2">
                <strong>{t.total_net}</strong>
              </td>
              <td style={{ textAlign: "right" }}>
                <span className="slip-total-amount">{total.toLocaleString(undefined, { minimumFractionDigits: 2, maximumFractionDigits: 2 })} ฿</span>
              </td>
            </tr>
          </tfoot>
        </table>

        {/* PromptPay Section */}
        {!isPaid ? (
          <div className="slip-payment-section">
            <div className="promptpay-badge-header">
              <span className="promptpay-icon">📱</span>
              <b>{t.pp_sec_title}</b>
            </div>
            <div className="promptpay-box">
              <div className="promptpay-qr-wrap">
                <div className="promptpay-qr-header">{t.pp_badge}</div>
                <div className="qr-svg-container" style={{ minHeight: 140, display: "flex", alignItems: "center", justifyContent: "center" }}>
                  {!imgError ? (
                    <img
                      src={qrUrl}
                      alt={`PromptPay QR ${total} THB`}
                      width="140"
                      height="140"
                      style={{ borderRadius: 6, display: "block" }}
                      onError={() => setImgError(true)}
                    />
                  ) : (
                    <div style={{ width: 140, height: 140, background: "#f3f4f6", display: "flex", alignItems: "center", justifyContent: "center", fontSize: 11, color: "#666", textAlign: "center", padding: 8 }}>
                      {t.pp_lbl}<br /><strong>{PROMPTPAY_FORMATTED}</strong>
                    </div>
                  )}
                </div>
                <div className="promptpay-qr-scan-note">{t.pp_scan_note}</div>
              </div>

              <div className="promptpay-text-details">
                <div className="pp-row">
                  <span className="pp-lbl">{t.acc_name_lbl}</span>
                  <span className="pp-val">{PROMPTPAY_NAME}</span>
                </div>
                <div className="pp-row">
                  <span className="pp-lbl">{t.pp_lbl}</span>
                  <span className="pp-val font-mono" style={{ fontSize: 16, color: "var(--primary)" }}>{PROMPTPAY_FORMATTED}</span>
                  <button type="button" className="btn-copy-pp" onClick={handleCopyPromptPay} title="Copy PromptPay Number">
                    {copied ? t.btn_copied : t.btn_copy}
                  </button>
                </div>
                <div className="pp-row">
                  <span className="pp-lbl">{t.transfer_amt_lbl}</span>
                  <span className="pp-val highlight-pay">{total.toLocaleString(undefined, { minimumFractionDigits: 2, maximumFractionDigits: 2 })} {t.baht}</span>
                  <span style={{ fontSize: 11, color: "var(--ink-muted)", fontStyle: "italic" }}>{t.locked_note}</span>
                </div>
                <div className="pp-notice">
                  {t.lock_notice(total.toLocaleString(undefined, { minimumFractionDigits: 2, maximumFractionDigits: 2 }))}
                </div>

                <div style={{ marginTop: 12, display: "flex", justifyContent: "flex-end" }}>
                  <button
                    type="button"
                    onClick={handleConfirmPaid}
                    disabled={verifying}
                    style={{
                      background: "linear-gradient(135deg, #059669 0%, #047857 100%)",
                      color: "#ffffff",
                      border: "none",
                      padding: "8px 16px",
                      borderRadius: 8,
                      fontSize: 13,
                      fontWeight: 700,
                      display: "inline-flex",
                      alignItems: "center",
                      gap: 6,
                      cursor: "pointer",
                      boxShadow: "0 2px 6px rgba(5, 150, 105, 0.3)",
                    }}
                  >
                    <span>{verifying ? "⏳" : "⚡"}</span>
                    <span>
                      {verifying
                        ? (lang === "en" ? "Verifying..." : "กำลังตรวจสอบ...")
                        : (lang === "en" ? "I have paid (Verify Now)" : "ฉันโอนเงินแล้ว (ตรวจสอบทันที)")}
                    </span>
                  </button>
                </div>
              </div>
            </div>
          </div>
        ) : (
          <div className="slip-paid-stamp">
            <div className="paid-seal">
              <span className="paid-seal-check">✓</span>
              <span className="paid-seal-text">{t.paid_seal}</span>
              {currentBill.paid_at && (
                <span className="paid-seal-date">
                  {t.paid_date(new Date(currentBill.paid_at).toLocaleDateString(lang === "en" ? "en-US" : "th-TH"))}
                </span>
              )}
            </div>
          </div>
        )}

        <div className="slip-footer-note">
          {t.footer_note}
        </div>
      </div>

      {/* Modal Actions */}
      <div className="modal-actions slip-actions" style={{ display: "flex", justifyContent: "space-between", alignItems: "center", gap: 10, marginTop: 16 }}>
        <div>
          {isOwner && !isEditing && (
            <button
              type="button"
              className="btn-secondary"
              onClick={handleStartEdit}
              style={{
                background: "#ecfdf5",
                color: "#047857",
                border: "1.5px solid #10b981",
                fontWeight: 700,
                display: "inline-flex",
                alignItems: "center",
                gap: 6,
              }}
            >
              <span>{t.btn_edit_prices}</span>
            </button>
          )}

          {isEditing && (
            <div style={{ display: "flex", gap: 8 }}>
              <button
                type="button"
                className="btn-primary"
                onClick={handleSavePrices}
                disabled={saving}
                style={{
                  background: "linear-gradient(135deg, #0f5144 0%, #166534 100%)",
                  fontWeight: 700,
                  display: "inline-flex",
                  alignItems: "center",
                  gap: 6,
                }}
              >
                <span>{saving ? t.btn_saving : t.btn_save_prices}</span>
              </button>
              <button
                type="button"
                className="btn-ghost"
                onClick={() => setIsEditing(false)}
                disabled={saving}
              >
                {t.btn_cancel_edit}
              </button>
            </div>
          )}
        </div>

        <div style={{ display: "flex", gap: 8 }}>
          {!isEditing && (
            <button type="button" className="btn-ghost" onClick={handlePrint}>
              {t.btn_print}
            </button>
          )}
          <button type="button" className="btn-primary" onClick={onClose}>
            {t.btn_close}
          </button>
        </div>
      </div>
    </Modal>
  );
}
